def import_local_file(
    source_file: Path,
    course_code: str,
    category_name: str,
    title: str,
    description: Optional[str] = None,
    db: Optional[Session] = None,
) -> Resource:
    """
    Developer-only utility to import an original local file into the platform.
    The same trimmed title + course updates one record. New content is stored
    separately and only replaces the old reference after a successful commit.
    This function owns the transaction, including for a supplied session.
    """
    title = title.strip()
    if not title or len(title) > 255:
        raise ValueError("Resource title must contain between 1 and 255 characters.")
    mime_type = validate_file(source_file)

    owns_session = False
    if db is None:
        db = SessionLocal()
        owns_session = True

    created_path = None
    committed = False
    try:
        # Resolve course
        course = db.execute(select(Course).where(Course.code == course_code.strip())).scalar_one_or_none()
        if not course:
            raise ValueError(f"Course with code '{course_code}' does not exist.")

        # Resolve category
        category = db.execute(select(Category).where(Category.name == category_name.strip())).scalar_one_or_none()
        if not category:
            raise ValueError(f"Category with name '{category_name}' does not exist.")

        # Resolve the existing record before creating any storage file.
        existing = db.execute(
            select(Resource).where(
                Resource.course_id == course.id,
                Resource.title == title,
            )
        ).scalar_one_or_none()
        previous_name = existing.file_path if existing else None

        # Titles and user filenames never become storage paths. Exclusive creation
        # protects existing bytes even in the extraordinarily unlikely UUID clash.
        target_name = f"resource_{uuid4().hex}{source_file.suffix.lower()}"
        target_path = STORAGE_DIR / target_name
        STORAGE_DIR.mkdir(parents=True, exist_ok=True)
        with target_path.open("xb") as destination:
            created_path = target_path
            with source_file.open("rb") as source:
                shutil.copyfileobj(source, destination)
        # Validate the stored snapshot as well: the source could change while copied.
        mime_type = validate_file(target_path)
        file_size = target_path.stat().st_size

        if existing:
            existing.description = description
            existing.category_id = category.id
            existing.file_path = target_name
            existing.original_filename = source_file.name
            existing.mime_type = mime_type
            existing.file_size = file_size
            resource = existing
        else:
            resource = Resource(
                title=title,
                description=description,
                course_id=course.id,
                category_id=category.id,
                file_path=target_name,
                original_filename=source_file.name,
                mime_type=mime_type,
                file_size=file_size,
                download_count=0,
            )
            db.add(resource)

        db.commit()
        committed = True
        # A refresh failure after commit must never delete the committed file.
        db.refresh(resource)
        if previous_name:
            remove_replaced_file(db, previous_name, target_name)
        print(f"✅ Imported '{title}' (ID {resource.id}) -> {target_path}")
        return resource
    except Exception:
        try:
            db.rollback()
        except SQLAlchemyError:
            logger.exception("Could not roll back failed import transaction")
        if not committed and created_path is not None:
            try:
                created_path.unlink(missing_ok=True)
            except OSError:
                logger.exception("Could not remove failed import file %s", created_path)
        raise
    finally:
        if owns_session:
            db.close()


def main() -> None:
    parser = argparse.ArgumentParser(
        description="UniShare Developer CLI & Resource Management"
    )
    subparsers = parser.add_subparsers(dest="command")

    # Seed command
    seed_parser = subparsers.add_parser("seed", help="Initialize and seed demo data")
    seed_parser.add_argument(
        "--reset", action="store_true", help="Drop and recreate database schema before seeding"
    )

    # Import command
    import_parser = subparsers.add_parser("import-file", help="Import a local academic document")
    import_parser.add_argument("--file", required=True, type=Path, help="Path to local file")
    import_parser.add_argument("--course", required=True, help="Course code (e.g., 'CSE 3101')")
    import_parser.add_argument("--category", required=True, help="Category name (e.g., 'Lecture Notes')")
    import_parser.add_argument("--title", required=True, help="Resource title")
    import_parser.add_argument("--description", default=None, help="Resource description")

    args = parser.parse_args()

    # Default action if no command specified: seed
    if not args.command or args.command == "seed":
        init_db()
        db = SessionLocal()
        try:
            if getattr(args, "reset", False):
                print("⚠️ Reset flag detected: dropping and recreating tables...")
                from backend.app.database import Base, engine
                Base.metadata.drop_all(bind=engine)
                Base.metadata.create_all(bind=engine)
            seed_database(db)
        finally:
            db.close()

    elif args.command == "import-file":
        init_db()
        import_local_file(
            source_file=args.file,
            course_code=args.course,
            category_name=args.category,
            title=args.title,
            description=args.description,
        )


if __name__ == "__main__":
    main()
